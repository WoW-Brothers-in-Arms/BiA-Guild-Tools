# Writes the addon's static recipe data from the game's own tables, as wago.tools lists them for one
# client build:
#   BiAGuildTools/Modules/Professions/Categories.lua  names of all recipe categories (English, German) and
#                                                     their order in the game's profession window
#   BiAGuildTools/Modules/Professions/Recipes.lua     every recipe of the crafting professions with its
#                                                     category
# The game client names categories and tells a recipe's category only for a profession whose window is
# open; with these tables the addon needs neither.
#
# Run it for every new Forever client build before publishing (the release's pre-push check compares
# the build with the installed client, see scripts/check-game-data.sh):
#   python3 scripts/make-recipe-data.py 1.60.1.70938
import csv, io, os, sys, urllib.request

BUILD = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "BiAGuildTools", "Modules", "Professions")
URL = "https://wago.tools/db2/{table}/csv?build={build}&locale={locale}"
# The crafting professions of Data.lua (D.IsCrafting): Alchemy, Blacksmithing, Enchanting, Engineering,
# Leatherworking, Tailoring, Jewelcrafting, Inscription, Cooking, First Aid.
CRAFTING = {171, 164, 333, 202, 165, 197, 755, 773, 185, 129}
WIDTH = 120  # longest line of IDs (luacheck allows 140)


def table(name, locale="enUS"):
    request = urllib.request.Request(URL.format(table=name, build=BUILD, locale=locale),
                                     headers={"User-Agent": "addon-data-script"})
    with urllib.request.urlopen(request) as response:
        rows = list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))
    if not rows or "ID" not in rows[0]:
        sys.exit("no %s rows for build %s (%s)" % (name, BUILD, locale))
    return rows


def lua(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(filename, lines):
    with open(os.path.join(OUT, filename), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def header(filename, what):
    return [
        "-- %s: %s" % (filename, what[0]),
    ] + ["-- " + line for line in what[1:]] + [
        "-- Generated by scripts/make-recipe-data.py from the game's tables of client build %s; don't edit." % BUILD,
        "local _, ns = ...",
        "",
        'ns.ProfessionData.DATA_BUILD = "%s"' % BUILD,
    ]


# Categories
en = {int(r["ID"]): r for r in table("TradeSkillCategory") if r["Name_lang"]}
de = {int(r["ID"]): r for r in table("TradeSkillCategory", "deDE") if r["Name_lang"]}
lines = header("Categories.lua", ["names of the recipe categories, { [categoryID] = { English, German, order } }.",
                                  "order: the category's place in the game's profession window (lower first)."])
lines.append("ns.ProfessionData.CATEGORIES = {")
for cat in sorted(en):
    name = en[cat]["Name_lang"]
    german = de[cat]["Name_lang"] if cat in de else name
    lines.append("    [%d] = { %s, %s, %d }," % (cat, lua(name), lua(german), int(en[cat]["OrderIndex"] or 0)))
lines.append("}")
write("Categories.lua", lines)

# Recipes: SkillLineAbility ties a spell to its profession and category. Spells without a name are
# test or unreleased ones the game never shows.
named = {int(r["ID"]) for r in table("SpellName") if r["Name_lang"]}
recipes = {}  # [skill][spell] = category
for r in table("SkillLineAbility"):
    skill, spell, cat = int(r["SkillLine"]), int(r["Spell"]), int(r["TradeSkillCategoryID"])
    if skill in CRAFTING and cat in en and spell in named:
        old = recipes.setdefault(skill, {}).get(spell)
        recipes[skill][spell] = cat if old is None else min(old, cat)
lines = header("Recipes.lua", ["every recipe of the crafting professions by category,",
                               "{ [skillLine] = { [categoryID] = { recipeID, ... } } }, recipe IDs ascending."])
lines.append("ns.ProfessionData.RECIPES = {")
count = 0
for skill in sorted(recipes):
    lines.append("    [%d] = {" % skill)
    by_cat = {}
    for spell, cat in recipes[skill].items():
        by_cat.setdefault(cat, []).append(spell)
    for cat in sorted(by_cat):
        ids = sorted(by_cat[cat])
        count += len(ids)
        lines.append("        [%d] = {" % cat)
        line = "           "
        for spell in ids:
            part = " %d," % spell
            if len(line) + len(part) > WIDTH:
                lines.append(line)
                line = "           "
            line += part
        lines.append(line)
        lines.append("        },")
    lines.append("    },")
lines.append("}")
write("Recipes.lua", lines)
print("build %s: %d categories, %d recipes in %d professions" % (BUILD, len(en), count, len(recipes)))
