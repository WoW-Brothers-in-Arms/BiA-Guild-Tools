# Writes BiAGuildTools/Modules/Professions/Categories.lua: the names of all profession recipe categories
# in English and German, from the game's TradeSkillCategory table as wago.tools lists it for one build.
#
# The game client names a category only for professions the character has itself; for everybody else's
# recipes the window falls back to this table (see ProfessionData.CategoryName in Data.lua).
#
# Run again when Forever's client gets a new build (the version is in the launcher, or in
# "/Applications/World of Warcraft/.build.info", product "wowf"):
#   python3 scripts/make-recipe-categories.py 1.60.1.70938 BiAGuildTools/Modules/Professions/Categories.lua
import csv, io, sys, urllib.request

BUILD, OUT = sys.argv[1], sys.argv[2]
URL = "https://wago.tools/db2/TradeSkillCategory/csv?build={build}&locale={locale}"


def names(locale):
    request = urllib.request.Request(URL.format(build=BUILD, locale=locale),
                                     headers={"User-Agent": "addon-data-script"})
    with urllib.request.urlopen(request) as response:
        text = response.read().decode("utf-8")
    rows = list(csv.DictReader(io.StringIO(text)))
    if not rows or "Name_lang" not in rows[0]:
        sys.exit("no TradeSkillCategory rows for build %s (%s)" % (BUILD, locale))
    return {int(row["ID"]): row["Name_lang"] for row in rows if row["Name_lang"]}


def lua(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


en, de = names("enUS"), names("deDE")
lines = [
    "-- Categories.lua: names of the profession recipe categories, { [categoryID] = { English, German } }.",
    "-- Generated by scripts/make-recipe-categories.py from TradeSkillCategory, build %s; don't edit." % BUILD,
    "local _, ns = ...",
    "",
    "ns.ProfessionData.CATEGORIES = {",
]
for cat in sorted(en):
    lines.append("    [%d] = { %s, %s }," % (cat, lua(en[cat]), lua(de.get(cat, en[cat]))))
lines.append("}")
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("%d categories written to %s" % (len(en), OUT))
